#!/usr/bin/env node
/**
 * Generate EXPORT_LOCK_REPORT.md
 * node scripts/export-lock-report.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { EXPORT_LOCK_VERSION } from '../src/core/export/export-lock.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const gate = spawnSync('node', ['src/tests/qa-export-lock.mjs'], {
  cwd: root,
  encoding: 'utf8',
});
const gateOk = gate.status === 0;

let gateReport = {};
try {
  gateReport = JSON.parse(readFileSync(join(root, 'tests/output/export-lock/report.json'), 'utf8'));
} catch {
  gateReport = { pass: false, errors: ['report.json missing'] };
}

const indexHtml = readFileSync(join(root, 'index.html'), 'utf8');

const pipeline = [
  'OCR / extract',
  'normalizedText',
  'structuredResume',
  'resumeData',
  'finalResumeData',
  'cvData (getFinalCvData)',
  'renderCV → #cvDoc.cv-page.cv--live',
  'validateExportLock',
  'HirelyPdfExport.exportCvToPdf',
];

const acceptance = [
  { id: 'preview_parity', label: 'Exported CV matches preview (finalResumeData + DOM parity)', ok: gateReport.checks?.some((c) => c.label === 'export_lock_prep' && c.ok) },
  { id: 'sections', label: 'No missing sections (validateExportSectionParity)', ok: gateReport.checks?.some((c) => c.label === 'section parity' && c.ok) },
  { id: 'a4', label: 'No cropped A4 (multi-page preview allowed; PDF A4 validated)', ok: gateReport.checks?.some((c) => c.label === '4_export_cv_pdf' && c.ok) },
  { id: 'checklist', label: 'Export PDF checklist checked after success', ok: gateReport.checks?.some((c) => c.label === 'export_checklist_checked' && c.ok) },
  { id: 'letter', label: 'Cover letter exports when generated', ok: gateReport.checks?.some((c) => c.label === '5_export_letter_pdf' && c.ok) },
  { id: 'console', label: 'No fatal console errors', ok: gateReport.checks?.some((c) => c.label === 'no_fatal_console' && c.ok) },
];

const allAcceptance = acceptance.every((a) => a.ok);
const verdict = gateOk && allAcceptance ? 'PASS' : 'FAIL';

const failedChecks = (gateReport.checks || []).filter((c) => !c.ok);
const passedChecks = (gateReport.checks || []).filter((c) => c.ok);

const md = `# EXPORT LOCK REPORT

**Verdict: ${verdict}**

Generated: ${new Date().toISOString()}  
Lock version: \`${EXPORT_LOCK_VERSION}\`

## Mission

Make export reliable. PDF export uses the same \`finalResumeData\` and the same visible \`.cv-page\` (\`#cvDoc\`). Export checklist updates after successful PDF generation.

## Test flow

1. Import CV (paste fixture)
2. Review CV (studio / final contract)
3. Generate cover letter
4. Export CV PDF
5. Export cover letter PDF

## Acceptance criteria

| Criterion | Status |
|-----------|--------|
${acceptance.map((a) => `| ${a.label} | ${a.ok ? '✅' : '❌'} |`).join('\n')}

## Export pipeline (locked)

\`\`\`
${pipeline.join('\n → ')}
\`\`\`

## Implementation

| Component | Role |
|-----------|------|
| \`src/core/export/export-lock.js\` | \`validateExportLock\`, section parity, A4 metrics |
| \`index.html\` \`prepareLockedCvExport()\` | Renders \`getFinalCvData()\`, validates before PDF |
| \`index.html\` \`downloadPDF()\` | Uses prep lock + \`markCvExportChecklistDone()\` |
| \`index.html\` \`buildProductChecklist()\` | Adds \`export\` item from \`state.cvPdfExported\` |
| \`src/ui/export/hirely-pdf-export.js\` | A4 html2pdf export from live \`#cvDoc\` |

## Gate results

- QA command: \`npm run qa:export-lock\`
- Gate: ${gateOk ? '**PASSED**' : '**FAILED**'}
- Checks passed: ${passedChecks.length}
- Checks failed: ${failedChecks.length}

${failedChecks.length ? `### Failed checks\n\n${failedChecks.map((c) => `- **${c.label}**: ${c.detail || 'failed'}`).join('\n')}\n` : ''}

${gateReport.consoleErrors?.length ? `### Console errors\n\n${gateReport.consoleErrors.map((e) => `- \`${e}\``).join('\n')}\n` : ''}

## UI wiring (index.html)

- \`prepareLockedCvExport\`: ${indexHtml.includes('prepareLockedCvExport') ? 'present' : 'missing'}
- \`validateLockedCvExport\` → \`HirelyCore.validateExportLock\`: ${indexHtml.includes('validateLockedCvExport') ? 'present' : 'missing'}
- \`downloadPDF\` uses lock: ${indexHtml.slice(indexHtml.indexOf('async function downloadPDF'), indexHtml.indexOf('async function downloadPDF') + 800).includes('prepareLockedCvExport') ? 'yes' : 'no'}

---

*Report generated by \`scripts/export-lock-report.mjs\`*
`;

mkdirSync(root, { recursive: true });
writeFileSync(join(root, 'EXPORT_LOCK_REPORT.md'), md);

console.log(`EXPORT_LOCK_REPORT.md written — ${verdict}`);
process.exit(verdict === 'PASS' ? 0 : 1);
