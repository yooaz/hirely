lines.push(`| Body | \`--ds3-text-body\` | ${extractToken('--ds3-text-body')} | 400 | -0.012em |`);
lines.push(`| Caption | \`--ds3-text-caption\` | ${extractToken('--ds3-text-caption')} | 500–600 | — |`);
lines.push(`| Micro label | \`--ds3-text-micro\` | ${extractToken('--ds3-text-micro')} | 600 | +0.04em (uppercase) |`);
