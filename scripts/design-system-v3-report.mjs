#!/usr/bin/env node
/**
 * Generate DESIGN_SYSTEM_V3.md with QA gate status.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const cssPath = join(root, 'src/ui/design-system-v3.css');

const gate = spawnSync('node', ['src/tests/qa-design-system-v3.mjs'], { cwd: root, encoding: 'utf8' });
const gateOk = gate.status === 0;

const css = existsSync(cssPath) ? readFileSync(cssPath, 'utf8') : '';

function extractToken(name) {
  const m = css.match(new RegExp(`${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}:\\s*([^;]+);`));
  return m ? m[1].trim() : '—';
}

