lines.push('');
lines.push('## QA');
lines.push('');
lines.push('```bash');
lines.push('npm run qa:design-system-v3');
lines.push('npm run design-system-v3-report');
lines.push('```');
lines.push('');
lines.push('Checks: file presence, load order, token coverage, borderless rules, preview scaling, doc presence.');
lines.push('');
lines.push('## References');
lines.push('');
lines.push('- Apple Human Interface Guidelines — materials, typography scale, layered shadows');
lines.push('- Linear — compact controls, monochrome chrome, inset rings');
