lines.push('');
lines.push('## Mission');
lines.push('');
lines.push('Move Hirely product chrome from startup MVP toward **Apple · Linear · Arc Browser · Notion** — calm, typographic, borderless surfaces with a dominant CV canvas.');
lines.push('');
lines.push('## Design principles');
lines.push('');
lines.push('| Principle | V2 (MVP) | V3 (Premium) |');
lines.push('|-----------|----------|--------------|');
lines.push('| Borders | 1px everywhere | Hairline inset or none — elevation via shadow |');
lines.push('| Color | Blue/green/amber score rings | Monochrome ink scale |');
lines.push('| Hierarchy | Similar weights | Display → title → body → micro labels |');
lines.push('| Spacing | Tight panels | 4px grid, generous canvas breathing room |');
lines.push('| Controls | 10–12px buttons | 11–12px caption controls, ink primary CTA |');
lines.push('| Preview | ~62vh stage | **72vh** stage + container scale up to **1.22×** |');
lines.push('| Side rails | 168–220px | **132–196px** — preview wins |');
lines.push('');
lines.push('## Load order');
lines.push('');
lines.push('```');
lines.push('studio-layout.css');
lines.push('hirely-premium-polish.css');
lines.push('hirely-ui-scale.css');
lines.push('design-system-v3.css   ← wins (this system)');
lines.push('```');
lines.push('');
lines.push('**File:** `src/ui/design-system-v3.css`');
lines.push('');
lines.push('## Color system (fewer colors)');
lines.push('');
lines.push('| Token | Value | Role |');
lines.push('|-------|-------|------|');
lines.push(`| \`--ds3-bg\` | ${extractToken('--ds3-bg')} | App shell |`);
lines.push(`| \`--ds3-surface\` | ${extractToken('--ds3-surface')} | Cards, panels |`);
lines.push(`| \`--ds3-surface-sunken\` | ${extractToken('--ds3-surface-sunken')} | Inset wells, progress hint |`);
lines.push(`| \`--ds3-canvas\` | ${extractToken('--ds3-canvas')} | CV preview stage (Arc-style) |`);
