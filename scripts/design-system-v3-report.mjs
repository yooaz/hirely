lines.push('- **CV stage:** `min(72vh, 920px)` with sunken `--ds3-canvas` background');
lines.push('- **Preview scale:** `@container cv-canvas` — up to **1.22×** on wide viewports');
lines.push('');
lines.push('## Components');
