lines.push(`| \`--ds3-ink-secondary\` | ${extractToken('--ds3-ink-secondary')} | Secondary copy |`);
lines.push(`| \`--ds3-ink-tertiary\` | ${extractToken('--ds3-ink-tertiary')} | Labels, hints |`);
lines.push(`| \`--ds3-accent-soft\` | ${extractToken('--ds3-accent-soft')} | Hover washes |`);
lines.push('');
lines.push('Semantic greens/ambers/roses in chrome are **remapped to ink** — color reserved for CV template content only.');
lines.push('');
lines.push('## Typography (more hierarchy)');
lines.push('');
lines.push('| Role | Token | Size | Weight | Tracking |');
lines.push('|------|-------|------|--------|----------|');
lines.push(`| Display | \`--ds3-text-display\` | ${extractToken('--ds3-text-display')} | 650 | -0.035em |`);
